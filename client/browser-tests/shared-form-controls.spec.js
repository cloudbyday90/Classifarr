test('tag editor waits for composition and does not repeat empty Backspace removals', async ({ page }) => {
  await page.goto('/browser-tests/fixtures/shared-form-controls.html')
  const input = page.getByRole('textbox', { name: 'Keywords', exact: true })
  await input.focus()
  // Synthetic composition protocol coverage; this is not an OS/IME certification.
  await input.dispatchEvent('compositionstart')
  await input.fill('日本語')
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(page.getByLabel('Tag deliveries')).toHaveText('0')
  await input.dispatchEvent('compositionend')
  await input.press('Enter')
  await expect(page.getByLabel('Tag values')).toHaveText('["first","last","日本語"]')
  await input.press('Backspace')
  await input.dispatchEvent('keydown', { key: 'Backspace', repeat: true })
  await expect(page.getByLabel('Tag values')).toHaveText('["first","last"]')
  await expect(page.getByLabel('Tag deliveries')).toHaveText('2')
  await input.dispatchEvent('compositionstart')
  await input.fill('中文')
  await input.evaluate(element => {
    element.blur()
    element.dispatchEvent(new globalThis.CompositionEvent('compositionend', { bubbles: true }))
    element.dispatchEvent(new globalThis.Event('input', { bubbles: true }))
  })
  await expect(page.getByLabel('Tag values')).toHaveText('["first","last","中文"]')
  await expect(input).toHaveValue('')
  await input.focus()
  await input.dispatchEvent('compositionstart')
  await input.fill('再見')
  await input.evaluate(element => element.blur())
  await page.getByRole('button', { name: 'Add tag to Keywords', exact: true }).focus()
  await input.dispatchEvent('compositionend')
  await expect(page.getByLabel('Tag deliveries')).toHaveText('3')
  await expect(input).toHaveValue('再見')
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Tag values')).toHaveText('["first","last","中文","再見"]')
  await expect(page.getByLabel('Tag deliveries')).toHaveText('4')
  await expect(page.getByLabel('Tag submissions')).toHaveText('0')
})

