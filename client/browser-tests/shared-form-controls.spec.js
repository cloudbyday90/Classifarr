  await expect(page.getByLabel('Tag values')).toHaveText('["last","draft"]')
  const remove = page.getByRole('button', { name: 'Remove last from Keywords', exact: true })
  await remove.focus()
  await remove.press('Space')
  await expect(input).toBeFocused()
  await page.getByRole('button', { name: 'Remove draft from Keywords', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(input).toBeFocused()
  await expect(page.getByLabel('Tag values')).toHaveText('[]')
  await input.fill('touch')
  await add.click()
  await expect(input).toBeFocused()
  await input.fill('blur')
  await input.press('Tab')
  await expect(add).toBeFocused()
  await expect(page.getByLabel('Tag values')).toHaveText('["touch"]')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Save sample tags' })).toBeFocused()
